func isResponsesEqual(r1, r2 Response) bool {
	if r1.Command != r2.Command {
		return false
	}
	if r1.Status != r2.Status {
		return false
	}
	if !slices.Equal(r1.Data, r2.Data) {
		return false
	}
	return true
}

func TestUnpackEmptyDataCorrectCommandAndCrc(t *testing.T) {
	rawResponse := []byte{bcpSof, uint8(FlashCommand), bcpOk, 0x00, 0x00, 0x20}
	expectedResponse := Response{
		Command: FlashCommand,
		Status:  bcpOk,
		Data:    make([]byte, 0),
	}

	realResponse, err := unpackResponse(rawResponse)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if !isResponsesEqual(realResponse, expectedResponse) {
		t.Fatalf(
			"wrong parsing of response:\ngot:  %+v\nwant: %+v",
			realResponse,
			expectedResponse,
		)
	}
}

